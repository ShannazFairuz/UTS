CREATE TABLE jenis_produk (
    id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama  varchar(100) NOT NULL,
    CONSTRAINT uq_jenis_produk_nama UNIQUE (nama),
    CONSTRAINT ck_jenis_produk_nama CHECK (btrim(nama) <> '')
);

CREATE TABLE pelanggan (
    id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode  varchar(20)  NOT NULL,
    nama  varchar(150) NOT NULL,
    kota  varchar(100) NOT NULL,
    CONSTRAINT uq_pelanggan_kode UNIQUE (kode),
    CONSTRAINT ck_pelanggan_kode CHECK (btrim(kode) <> ''),
    CONSTRAINT ck_pelanggan_nama CHECK (btrim(nama) <> ''),
    CONSTRAINT ck_pelanggan_kota CHECK (btrim(kota) <> '')
);

CREATE TABLE produk (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode          varchar(20)   NOT NULL,
    nama          varchar(150)  NOT NULL,
    id_jenis      integer       NOT NULL,
    satuan        varchar(20)   NOT NULL DEFAULT 'pcs',
    harga         numeric(14,2) NOT NULL,
    stok_minimum  integer       NOT NULL DEFAULT 0,
    CONSTRAINT uq_produk_kode UNIQUE (kode),
    CONSTRAINT fk_produk_jenis FOREIGN KEY (id_jenis)
        REFERENCES jenis_produk (id),
    CONSTRAINT ck_produk_kode CHECK (btrim(kode) <> ''),
    CONSTRAINT ck_produk_nama CHECK (btrim(nama) <> ''),
    CONSTRAINT ck_produk_harga CHECK (harga >= 0),
    CONSTRAINT ck_produk_stok_minimum CHECK (stok_minimum >= 0)
);

CREATE TABLE produksi (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal      timestamptz NOT NULL DEFAULT now(),
    id_produk    integer     NOT NULL,
    id_lini      integer     NOT NULL,
    jumlah_baik  integer     NOT NULL,
    jumlah_cacat integer     NOT NULL DEFAULT 0,
    CONSTRAINT fk_produksi_produk FOREIGN KEY (id_produk)
        REFERENCES produk (id),
    CONSTRAINT fk_produksi_lini FOREIGN KEY (id_lini)
        REFERENCES lini_produksi (id),
    CONSTRAINT ck_produksi_jumlah_baik CHECK (jumlah_baik >= 0),
    CONSTRAINT ck_produksi_jumlah_cacat CHECK (jumlah_cacat >= 0)
);

CREATE TABLE pengiriman (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal       timestamptz NOT NULL DEFAULT now(),
    id_produk     integer     NOT NULL,
    id_pelanggan  integer     NOT NULL,
    jumlah        integer     NOT NULL,
    CONSTRAINT fk_pengiriman_produk FOREIGN KEY (id_produk)
        REFERENCES produk (id),
    CONSTRAINT fk_pengiriman_pelanggan FOREIGN KEY (id_pelanggan)
        REFERENCES pelanggan (id),
    CONSTRAINT ck_pengiriman_jumlah CHECK (jumlah > 0)
);

CREATE INDEX idx_produk_id_jenis         ON produk (id_jenis);
CREATE INDEX idx_produksi_id_produk      ON produksi (id_produk);
CREATE INDEX idx_produksi_id_lini        ON produksi (id_lini);
CREATE INDEX idx_produksi_tanggal        ON produksi (tanggal);
CREATE INDEX idx_pengiriman_id_produk    ON pengiriman (id_produk);
CREATE INDEX idx_pengiriman_id_pelanggan ON pengiriman (id_pelanggan);
CREATE INDEX idx_pengiriman_tanggal      ON pengiriman (tanggal);

SELECT 'jenis_produk' AS tabel, count(*) AS baris FROM jenis_produk
 UNION ALL SELECT 'lini_produksi', count(*) FROM lini_produksi
UNION ALL SELECT 'pelanggan',     count(*) FROM pelanggan
UNION ALL SELECT 'produk',        count(*) FROM produk
UNION ALL SELECT 'produksi',      count(*) FROM produksi
UNION ALL SELECT 'pengiriman',    count(*) FROM pengiriman;

